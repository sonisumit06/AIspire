import React, { useState, useEffect, useRef } from 'react';
import {
  BookOpen,
  Search,
  ExternalLink,
  Video,
  FileText,
  Globe,
  Copy,
  Check,
  X,
  Bookmark,
  BookmarkCheck,
  Sparkles,
} from 'lucide-react';
import { CURATED_RESOURCES, EXAM_AND_SUBJECT_CATEGORIES } from '../data/resources';
import type { ResourceItem } from '../types';
import { generateDynamicResources } from '../services/geminiService';
import { useApp } from '../context/AppContext';
import { animateEntrance, animatePop } from '../utils/animations';
import { useButtonMotion } from '../hooks/useMotion';

export const ResourcesView: React.FC = () => {
  const containerRef = useRef<HTMLDivElement>(null);
  const { bookmarks, toggleBookmark } = useApp();
  const { handlePress } = useButtonMotion();

  const [searchQuery, setSearchQuery] = useState('');
  const [selectedCategory, setSelectedCategory] = useState<string>('all');
  const [activeTab, setActiveTab] = useState<'all' | 'google' | 'notes' | 'youtube' | 'saved'>('all');

  // Dynamic resources generated by search
  const [dynamicResources, setDynamicResources] = useState<ResourceItem[]>([]);
  const [isGenerating, setIsGenerating] = useState(false);

  // Active note for preview modal
  const [activeNote, setActiveNote] = useState<ResourceItem | null>(null);
  const [copiedNote, setCopiedNote] = useState(false);

  // All combined resources
  const allResources = [...dynamicResources, ...CURATED_RESOURCES];

  useEffect(() => {
    if (containerRef.current) {
      animateEntrance(containerRef.current.querySelectorAll('.resources-section'), {
        stagger: 45,
        translateY: [14, 0],
        duration: 650,
      });
    }
  }, [activeTab, selectedCategory, dynamicResources.length]);

  const handleToggleBookmark = (id: string, event?: React.MouseEvent) => {
    if (event?.currentTarget) {
      animatePop(event.currentTarget);
    }
    toggleBookmark(id);
  };

  // Filtered resources
  const filteredResources = allResources.filter((item) => {
    const matchesTab =
      activeTab === 'all' ||
      (activeTab === 'saved' ? bookmarks.includes(item.id) : item.type === activeTab);
    const matchesCat =
      selectedCategory === 'all' ||
      item.examOrSubjectId === selectedCategory ||
      item.category.toLowerCase().includes(selectedCategory.toLowerCase());

    const matchesQuery =
      searchQuery.trim() === '' ||
      item.title.toLowerCase().includes(searchQuery.toLowerCase()) ||
      item.description.toLowerCase().includes(searchQuery.toLowerCase()) ||
      item.tags.some((t) => t.toLowerCase().includes(searchQuery.toLowerCase()));

    return matchesTab && matchesCat && matchesQuery;
  });

  const handleDynamicSearch = async (e?: React.FormEvent) => {
    if (e) e.preventDefault();
    if (!searchQuery.trim()) return;

    setIsGenerating(true);
    try {
      const { googleResources, notesResources, youtubeResources } =
        await generateDynamicResources(searchQuery);

      setDynamicResources((prev) => [
        ...googleResources,
        ...notesResources,
        ...youtubeResources,
        ...prev,
      ]);
    } catch (err) {
      console.error(err);
    } finally {
      setIsGenerating(false);
    }
  };

  const copyNoteContent = (content?: string) => {
    if (!content) return;
    navigator.clipboard.writeText(content);
    setCopiedNote(true);
    setTimeout(() => setCopiedNote(false), 2000);
  };

  return (
    <div ref={containerRef} className="w-full max-w-6xl mx-auto px-4 sm:px-6 lg:px-8 py-8 space-y-8 min-w-0">
      {/* Header Banner */}
      <div className="resources-section bg-[#231A12] border border-[#6B523E] rounded-2xl p-5 sm:p-7 shadow-xl space-y-3 uiverse-card relative overflow-hidden w-full max-w-full min-w-0">
        <div
          className="absolute -top-20 -right-20 w-60 h-60 bg-[#6B4F3A]/20 rounded-full blur-3xl pointer-events-none"
          aria-hidden="true"
        />

        <div className="relative z-10 space-y-2">
          <span className="text-[11px] font-bold uppercase tracking-wider text-[#C9B79C] flex items-center gap-1.5">
            <Sparkles className="w-3.5 h-3.5" />
            <span>Academic Knowledge &amp; Examination Portals</span>
          </span>
          <h1 className="text-2xl sm:text-3xl font-bold text-[#FAF7F2] tracking-tight">
            Curated Study Resources, Exam Syllabi &amp; Video Courses
          </h1>
          <p className="text-xs sm:text-sm text-[#E2D5C3] max-w-3xl leading-relaxed">
            Search the open web for competitive entrance examinations, university coursework, and technical skills. Access official syllabus links, high-yield formula notes, and open-source video masterclasses.
          </p>
        </div>
      </div>

      {/* Search Bar */}
      <form
        onSubmit={handleDynamicSearch}
        className="resources-section bg-[#231A12] border border-[#6B523E] p-2.5 sm:p-3 rounded-2xl shadow-xl flex flex-col sm:flex-row items-center gap-2.5 uiverse-card w-full max-w-full min-w-0"
      >
        <div className="relative flex-1 w-full">
          <Search className="w-4 h-4 text-[#E2D5C3] absolute left-4 top-1/2 -translate-y-1/2" />
          <input
            type="text"
            placeholder="Search exam or topic (e.g. SAT Math, NEET Biology, System Design, GRE Quant, Python)..."
            value={searchQuery}
            onChange={(e) => setSearchQuery(e.target.value)}
            className="w-full pl-11 pr-4 py-2.5 bg-[#2B2118] border border-[#6B523E] rounded-xl text-xs sm:text-sm text-[#FAF7F2] placeholder-[#D8C7B0]/70 focus:outline-none focus:border-[#C9B79C] transition"
          />
        </div>

        <button
          type="submit"
          disabled={isGenerating || !searchQuery.trim()}
          className="w-full sm:w-auto px-5 py-2.5 bg-[#6B4F3A] hover:bg-[#7E5D45] disabled:opacity-50 text-[#FAF7F2] rounded-xl text-xs font-semibold shadow-md transition flex items-center justify-center gap-2 cursor-pointer flex-shrink-0 border border-[#C9B79C]/40 uiverse-btn"
        >
          <span>{isGenerating ? 'Searching...' : 'Search Resources'}</span>
        </button>
      </form>

      {/* Navigation Tabs & Discipline Filter */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 border-b border-[#6B523E] pb-4">
        {/* Resource Type Tabs */}
        <div className="flex items-center gap-1.5 overflow-x-auto pb-1 scrollbar-none">
          {(
            [
              { id: 'all', label: 'All Resources', count: allResources.length },
              { id: 'google', label: 'Official Portals', count: allResources.filter(r => r.type === 'google').length },
              { id: 'notes', label: 'Study Notes', count: allResources.filter(r => r.type === 'notes').length },
              { id: 'youtube', label: 'Video Courses', count: allResources.filter(r => r.type === 'youtube').length },
              { id: 'saved', label: 'Saved Bookmarks', count: bookmarks.length },
            ] as const
          ).map((tab) => {
            const isActive = activeTab === tab.id;
            return (
              <button
                key={tab.id}
                onClick={(e) => {
                  handlePress(e);
                  setActiveTab(tab.id);
                }}
                className={`px-3 py-1.5 rounded-xl text-xs font-semibold whitespace-nowrap transition cursor-pointer uiverse-btn ${
                  isActive
                    ? 'bg-[#6B4F3A] text-[#FAF7F2] shadow-sm border border-[#C9B79C]/40'
                    : 'bg-[#231A12] text-[#E2D5C3] hover:text-[#FAF7F2] border border-[#6B523E]'
                }`}
              >
                <span>{tab.label}</span>
                <span className={`ml-1.5 text-[10px] px-1.5 py-0.2 rounded-full ${
                  isActive ? 'bg-[#2B2118] text-[#FAF7F2]' : 'bg-[#2B2118] text-[#E2D5C3]'
                }`}>
                  {tab.count}
                </span>
              </button>
            );
          })}
        </div>

        {/* Discipline / Examination Category Selector */}
        <div className="flex items-center gap-2 flex-shrink-0">
          <span className="text-xs text-[#E2D5C3] hidden sm:inline">Discipline:</span>
          <select
            value={selectedCategory}
            onChange={(e) => setSelectedCategory(e.target.value)}
            className="px-3 py-1.5 bg-[#2B2118] border border-[#6B523E] rounded-xl text-xs font-semibold text-[#FAF7F2] focus:outline-none focus:border-[#C9B79C] transition cursor-pointer"
          >
            <option value="all">All Disciplines &amp; Exams</option>
            {EXAM_AND_SUBJECT_CATEGORIES.map((cat) => (
              <option key={cat.id} value={cat.id}>
                {cat.name}
              </option>
            ))}
          </select>
        </div>
      </div>

      {/* Resources Cards Grid */}
      {filteredResources.length === 0 ? (
        <div className="resources-section text-center py-16 bg-[#231A12] border border-[#6B523E] rounded-2xl p-8 space-y-3 uiverse-card shadow-xl">
          <BookOpen className="w-8 h-8 text-[#E2D5C3] mx-auto" />
          <h3 className="text-base font-semibold text-[#FAF7F2]">No resources found</h3>
          <p className="text-xs text-[#E2D5C3] max-w-md mx-auto">
            {activeTab === 'saved'
              ? 'You have not saved any bookmarks yet. Click the bookmark icon on any guide or video to save it.'
              : 'Try adjusting your search query or switching category filters.'}
          </p>
        </div>
      ) : (
        <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-4">
          {filteredResources.map((item) => {
            const isBookmarked = bookmarks.includes(item.id);
            const isNote = item.type === 'notes';
            const isVideo = item.type === 'youtube';
            const isOfficial = item.type === 'google';

            return (
              <div
                key={item.id}
                className="resources-section bg-[#231A12] border border-[#6B523E] hover:border-[#8C6D53] rounded-2xl p-5 shadow-xl transition-all duration-300 flex flex-col justify-between space-y-4 group uiverse-card"
              >
                <div className="space-y-2.5">
                  {/* Category, Badge & Bookmark Action */}
                  <div className="flex items-center justify-between gap-2">
                    <div className="flex items-center gap-1.5 flex-wrap">
                      <span className="text-[10px] font-semibold uppercase tracking-wider px-2 py-0.5 rounded bg-[#2B2118] text-[#C9B79C] border border-[#6B523E]">
                        {item.category}
                      </span>
                      {item.badge && (
                        <span className="text-[10px] font-semibold px-2 py-0.5 rounded bg-[#6B4F3A]/40 text-[#FAF7F2] border border-[#C9B79C]/30">
                          {item.badge}
                        </span>
                      )}
                    </div>

                    <button
                      type="button"
                      onClick={(e) => handleToggleBookmark(item.id, e)}
                      className={`p-1.5 rounded-lg transition cursor-pointer border uiverse-btn ${
                        isBookmarked
                          ? 'text-[#FAF7F2] bg-[#6B4F3A] border-[#C9B79C]'
                          : 'text-[#E2D5C3] hover:text-[#FAF7F2] hover:bg-[#2B2118] border-transparent'
                      }`}
                      title={isBookmarked ? 'Remove Bookmark' : 'Save Bookmark'}
                    >
                      {isBookmarked ? (
                        <BookmarkCheck className="w-4 h-4 text-[#C9B79C]" />
                      ) : (
                        <Bookmark className="w-4 h-4" />
                      )}
                    </button>
                  </div>

                  {/* Title */}
                  <h3 className="text-sm sm:text-base font-bold text-[#FAF7F2] group-hover:text-[#C9B79C] transition leading-snug line-clamp-2">
                    {item.title}
                  </h3>

                  {/* Description */}
                  <p className="text-xs text-[#E2D5C3] leading-relaxed line-clamp-3">
                    {item.description}
                  </p>

                  {/* Tags */}
                  <div className="flex items-center gap-1 flex-wrap pt-1">
                    {item.tags.slice(0, 3).map((tag, tIdx) => (
                      <span
                        key={tIdx}
                        className="text-[10px] px-1.5 py-0.5 rounded bg-[#2B2118] text-[#FAF7F2] border border-[#6B523E]"
                      >
                        #{tag}
                      </span>
                    ))}
                  </div>
                </div>

                {/* Footer Action */}
                <div className="pt-3 border-t border-[#6B523E] flex items-center justify-between text-xs">
                  <span className="text-[11px] text-[#E2D5C3] truncate max-w-[150px] font-medium">
                    {item.authorOrSource}
                  </span>

                  {isNote ? (
                    <button
                      type="button"
                      onClick={() => setActiveNote(item)}
                      className="px-3 py-1.5 bg-[#2B2118] hover:bg-[#382B20] text-[#FAF7F2] border border-[#6B523E] rounded-xl font-medium transition flex items-center gap-1.5 cursor-pointer uiverse-btn"
                    >
                      <FileText className="w-3.5 h-3.5 text-[#C9B79C]" />
                      <span>Read Notes</span>
                    </button>
                  ) : isVideo ? (
                    <a
                      href={item.url}
                      target="_blank"
                      rel="noopener noreferrer"
                      className="px-3 py-1.5 bg-[#6B4F3A]/30 hover:bg-[#6B4F3A]/50 text-[#FAF7F2] border border-[#C9B79C]/30 rounded-xl font-medium transition flex items-center gap-1.5 uiverse-btn"
                    >
                      <Video className="w-3.5 h-3.5 text-[#C9B79C]" />
                      <span>Watch Course</span>
                    </a>
                  ) : (
                    <a
                      href={item.url}
                      target="_blank"
                      rel="noopener noreferrer"
                      className="px-3 py-1.5 bg-[#6B4F3A]/30 hover:bg-[#6B4F3A]/50 text-[#FAF7F2] border border-[#C9B79C]/30 rounded-xl font-medium transition flex items-center gap-1.5 uiverse-btn"
                    >
                      <Globe className="w-3.5 h-3.5 text-[#C9B79C]" />
                      <span>{isOfficial ? 'Open Portal' : 'Search Web'}</span>
                      <ExternalLink className="w-3 h-3" />
                    </a>
                  )}
                </div>
              </div>
            );
          })}
        </div>
      )}

      {/* Note Reader Modal */}
      {activeNote && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/75 backdrop-blur-sm animate-fadeIn">
          <div className="relative w-full max-w-2xl bg-[#231A12] border border-[#6B523E] rounded-2xl shadow-2xl overflow-hidden flex flex-col max-h-[85vh] uiverse-card">
            <div className="p-4 sm:p-5 border-b border-[#6B523E] flex items-center justify-between gap-3 bg-[#2B2118]">
              <div className="flex items-center gap-2.5">
                <div className="w-8 h-8 rounded-xl bg-[#6B4F3A]/40 text-[#FAF7F2] flex items-center justify-center border border-[#C9B79C]/30">
                  <FileText className="w-4 h-4 text-[#C9B79C]" />
                </div>
                <div>
                  <h3 className="text-sm sm:text-base font-bold text-[#FAF7F2] truncate max-w-md">
                    {activeNote.title}
                  </h3>
                  <span className="text-[11px] text-[#E2D5C3]">
                    {activeNote.authorOrSource}
                  </span>
                </div>
              </div>

              <div className="flex items-center gap-2">
                <button
                  type="button"
                  onClick={() => copyNoteContent(activeNote.notesContent)}
                  className="p-1.5 rounded-xl text-[#C9B79C] hover:text-[#FAF7F2] hover:bg-[#382B20] transition cursor-pointer border border-transparent hover:border-[#6B523E] uiverse-btn"
                  title="Copy to clipboard"
                >
                  {copiedNote ? <Check className="w-4 h-4 text-[#C9B79C]" /> : <Copy className="w-4 h-4" />}
                </button>
                <button
                  type="button"
                  onClick={() => setActiveNote(null)}
                  className="p-1.5 rounded-xl text-[#C9B79C] hover:text-[#FAF7F2] hover:bg-[#382B20] transition cursor-pointer border border-transparent hover:border-[#6B523E] uiverse-btn"
                >
                  <X className="w-5 h-5" />
                </button>
              </div>
            </div>

            <div className="p-6 overflow-y-auto text-xs sm:text-sm text-[#FAF7F2] leading-relaxed font-sans whitespace-pre-wrap">
              {activeNote.notesContent || activeNote.description}
            </div>
          </div>
        </div>
      )}
    </div>
  );
};
